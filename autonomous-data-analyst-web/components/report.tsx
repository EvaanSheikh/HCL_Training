"use client";

import { Section } from "./section";

function downloadReport(content: string) {
  const blob = new Blob([content], { type: "text/markdown;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement("a");
  anchor.href = url;
  anchor.download = "noha-analysis-report.md";
  anchor.click();
  URL.revokeObjectURL(url);
}

/** Shows the backend's final_report exactly as returned with download option. */
export function ReportSection({ report }: { report: string }) {
  return (
    <Section title="Final report" note="Raw report generated by the backend.">
      {report.trim() === "" ? (
        <p className="text-[15px] text-muted">The backend returned no report.</p>
      ) : (
        <div className="space-y-3">
          <div className="flex justify-end">
            <button
              type="button"
              onClick={() => downloadReport(report)}
              className="border border-line bg-surface px-3 py-1 font-mono text-[11px] uppercase tracking-wider text-muted transition-colors hover:border-ink hover:text-ink"
            >
              Download Report (.md) ↓
            </button>
          </div>
          <details className="group border border-line bg-surface" open>
            <summary className="mono-label flex cursor-pointer list-none items-center justify-between px-4 py-3 transition-colors hover:!text-ink">
              <span>
                <span
                  className="mr-2 inline-block transition-transform duration-150 group-open:rotate-90"
                  aria-hidden
                >
                  ›
                </span>
                Report ({report.split("\n").length} lines)
              </span>
            </summary>
            <pre className="max-h-[480px] overflow-auto whitespace-pre-wrap break-words border-t border-line p-4 font-mono text-[12.5px] leading-6">
              {report}
            </pre>
          </details>
        </div>
      )}
    </Section>
  );
}
